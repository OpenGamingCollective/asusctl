/// Render the default cell for one config-struct field.
///
/// The default comes from `serde_json::to_value(<Struct>::default())`, which
/// keeps unit-variant names (`Quiet`, `Power`) that a `ron::Value` round-trip
/// would collapse to `()`. Whether a `String` value is quoted depends on the
/// field type: `String` fields show the quoted literal, enum-typed fields show
/// the bare variant name.
fn default_cell(
    struct_name: &str,
    name: &str,
    ty: &syn::Type,
    value: Option<&serde_json::Value>,
) -> Result<String> {
    let Some(value) = value else {
        if is_option(ty) {
            return Ok("omitted (`None`)".to_owned());
        }
        bail!("field {struct_name}.{name} missing from serialized default");
    };
    Ok(match value {
        serde_json::Value::Null => "omitted (`None`)".to_owned(),
        serde_json::Value::Bool(b) => format!("`{b}`"),
        serde_json::Value::Number(n) => format!("`{n}`"),
        serde_json::Value::String(s) if is_string_type(ty) => format!("`\"{s}\"`"),
        serde_json::Value::String(s) => format!("`{s}`"),
        serde_json::Value::Object(o) if o.is_empty() => "`{}`".to_owned(),
        serde_json::Value::Array(a) if a.is_empty() => "`[]`".to_owned(),
        other => bail!(
            "field {struct_name}.{name} has a non-scalar default ({other}); extend the generator"
        ),
    })
}

fn unwrap_option(ty: &syn::Type) -> &syn::Type {
    let syn::Type::Path(path) = ty else {
        return ty;
    };
    if path.path.segments.len() != 1 || path.path.segments[0].ident != "Option" {
        return ty;
    }
    let syn::PathArguments::AngleBracketed(args) = &path.path.segments[0].arguments else {
        return ty;
    };
    args.args
        .iter()
        .find_map(|arg| match arg {
            syn::GenericArgument::Type(inner) => Some(inner),
            _ => None,
        })
        .unwrap_or(ty)
}

fn is_string_type(ty: &syn::Type) -> bool {
    let syn::Type::Path(path) = unwrap_option(ty) else {
        return false;
    };
    path.path
        .segments
        .last()
        .is_some_and(|seg| seg.ident == "String")
}

// --- per-device config tables ----------------------------------------------

fn json_map(value: &serde_json::Value) -> Result<&serde_json::Map<String, serde_json::Value>> {
    let serde_json::Value::Object(map) = value else {
        bail!("serialized config default is not a JSON object");
    };
    Ok(map)
}

/// Field table for a config struct parsed from source. With `defaults` a
/// Default column is added; `overrides` replaces specific default cells.
fn config_struct_table(
    root: &Path,
    rel: &str,
    struct_name: &str,
    defaults: Option<&serde_json::Map<String, serde_json::Value>>,
    overrides: &BTreeMap<&str, &str>,
) -> Result<String> {
    let file = parse_file(root, rel)?;
    let config = find_struct(&file, struct_name)
        .context(format!("struct {struct_name} not found in {rel}"))?;
    let mut out = format!("{GENERATED_HEADER}\n");
    if defaults.is_some() {
        out.push_str("| Field | Type | Default | Description |\n|---|---|---|---|\n");
    } else {
        out.push_str("| Field | Type | Description |\n|---|---|---|\n");
    }
    for field in &config.fields {
        let name = field.ident.as_ref().unwrap().to_string();
        let doc = field_doc(field)?;
        if doc.is_empty() {
            bail!("field {struct_name}.{name} has no doc comment");
        }
        let ty = render_type(&file, &field.ty);
        if let Some(defaults) = defaults {
            let default = if let Some(text) = overrides.get(name.as_str()) {
                (*text).to_owned()
            } else if has_serde_skip(field) {
                "not written".to_owned()
            } else {
                default_cell(struct_name, &name, &field.ty, defaults.get(&name))?
            };
            out.push_str(&format!("| `{name}` | `{ty}` | {default} | {doc} |\n"));
        } else {
            out.push_str(&format!("| `{name}` | `{ty}` | {doc} |\n"));
        }
    }
    Ok(out)
}

