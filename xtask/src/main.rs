// --- asusctl command reference ---------------------------------------------

fn cli_help(root: &Path, path: &[String]) -> Result<String> {
    let mut cmd = Command::new("cargo");
    cmd.current_dir(root)
        .args([
            "run", "-q", "-p", "asusctl", "--",
        ])
        .args(path)
        .arg("--help");
    let output = cmd.output().with_context(|| {
        format!(
            "running `cargo run -q -p asusctl -- {} --help`",
            path.join(" ")
        )
    })?;
    if !output.status.success() {
        bail!(
            "`cargo run -q -p asusctl -- {} --help` failed:\n{}",
            path.join(" "),
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("asusctl help output is not valid UTF-8")
}

/// Subcommand names listed under a `Commands:` help section.
fn collect_commands(help: &str) -> Vec<String> {
    let Some(index) = help.lines().position(|line| line.trim() == "Commands:") else {
        return Vec::new();
    };
    help.lines()
        .skip(index + 1)
        .take_while(|line| !line.trim().is_empty())
        .filter_map(|line| line.split_whitespace().next())
        .map(str::to_owned)
        .collect()
}

fn asusctl_cli_md(root: &Path) -> Result<String> {
    let mut helps: BTreeMap<Vec<String>, String> = BTreeMap::new();
    let mut frontier: BTreeSet<Vec<String>> = BTreeSet::from([Vec::new()]);
    for depth in 0..=2 {
        let current: Vec<Vec<String>> = frontier.iter().cloned().collect();
        frontier.clear();
        for path in current {
            let help = cli_help(root, &path)?;
            if depth < 2 {
                for sub in collect_commands(&help) {
                    let mut child = path.clone();
                    child.push(sub);
                    frontier.insert(child);
                }
            }
            helps.insert(path, help);
        }
    }

    let mut out = String::from(GENERATED_HEADER);
    for (path, help) in &helps {
        let mut title = String::from("asusctl");
        for segment in path {
            title.push(' ');
            title.push_str(segment);
        }
        out.push_str(&format!(
            "\n## {title}\n\n```text\n{}\n```\n",
            help.trim_end_matches('\n')
        ));
    }
    Ok(out)
}

// --- armoury attribute table -----------------------------------------------

fn armoury_attributes_md(root: &Path) -> Result<String> {
    let file = parse_file(root, "rog-platform/src/asus_armoury.rs")?;
    let enumeration =
        find_enum(&file, "FirmwareAttribute").context("enum FirmwareAttribute not found")?;

    let mut out =
        format!("{GENERATED_HEADER}\n| `asusctl` name | RON variant | Type |\n|---|---|---|\n");
    for variant in &enumeration.variants {
        let name = variant.ident.to_string();
        if name == "PendingReboot" || name == "None" {
            continue;
        }
        let attr: FirmwareAttribute = ron::from_str(&name)
            .with_context(|| format!("parsing FirmwareAttribute variant {name} as RON"))?;
        out.push_str(&format!(
            "| `{}` | `{name}` | `{:?}` |\n",
            <&str>::from(attr),
            attr.property_type()
        ));
    }
    Ok(out)
}

// --- service unit table -----------------------------------------------------

fn services_md(root: &Path) -> Result<String> {
    let dir = root.join("data");
    let mut units: Vec<String> = fs::read_dir(&dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            (path.extension()?.to_str()? == "service")
                .then(|| path.file_name().unwrap().to_string_lossy().into_owned())
        })
        .collect();
    units.sort();

    let mut out = format!(
        "{GENERATED_HEADER}\n| Unit | Type | PartOf | Requires | ExecStart | TimeoutStopSec |\n|---|---|---|---|---|---|\n"
    );
    for unit in units {
        let text =
            fs::read_to_string(dir.join(&unit)).with_context(|| format!("reading {unit}"))?;
        let mut typ = None;
        let mut part_of: Vec<&str> = Vec::new();
        let mut requires: Vec<&str> = Vec::new();
        let mut exec_start = None;
        let mut timeout_stop = None;
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') || line.starts_with('[') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            match key.trim() {
                "Type" => {
                    typ.get_or_insert(value.trim());
                }
                "PartOf" => push_unique(&mut part_of, value),
                "Requires" => push_unique(&mut requires, value),
                "ExecStart" => {
                    exec_start.get_or_insert(value.trim());
                }
                "TimeoutStopSec" => {
                    timeout_stop.get_or_insert(value.trim());
                }
                _ => continue,
            };
        }
        out.push_str(&format!(
            "| `{unit}` | {} | {} | {} | {} | {} |\n",
            cell(typ),
            list_cell(&part_of),
            list_cell(&requires),
            cell(exec_start),
            cell(timeout_stop),
        ));
    }
    Ok(out)
}

fn push_unique<'a>(list: &mut Vec<&'a str>, value: &'a str) {
    for token in value.split_whitespace() {
        if !list.contains(&token) {
            list.push(token);
        }
    }
}

fn cell(value: Option<&str>) -> String {
    match value {
        Some(value) => format!("`{value}`"),
        None => "-".to_owned(),
    }
}

fn list_cell(values: &[&str]) -> String {
    if values.is_empty() {
        return "-".to_owned();
    }
    values
        .iter()
        .map(|value| format!("`{value}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

