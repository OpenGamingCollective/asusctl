fn check_ledcode_table(root: &Path, errors: &mut usize) -> Result<()> {
    let docs = read_rel(root, "docs/configuration/asusd-user.md")?;
    let documented = zones_table_tokens(&docs);

    let file = parse_file(root, "rog-aura/src/keyboard/advanced.rs")?;
    let enumeration = find_enum(&file, "LedCode").context("enum LedCode not found")?;
    let variants: BTreeSet<String> = enumeration
        .variants
        .iter()
        .map(|variant| variant.ident.to_string())
        .collect();

    report_mismatch("LedCode", &variants, &documented, errors);
    Ok(())
}

/// Backticked variant-shaped tokens from the table data rows of the
/// `### Zones` section (the `LedCode` tables).
fn zones_table_tokens(docs: &str) -> BTreeSet<String> {
    let mut tokens = BTreeSet::new();
    let mut in_section = false;
    let mut in_data_rows = false;
    for line in docs.lines() {
        if !in_section {
            in_section = line.trim() == "### Zones";
            continue;
        }
        if line.starts_with("## ") {
            break;
        }
        let trimmed = line.trim();
        if !trimmed.starts_with('|') {
            in_data_rows = false;
            continue;
        }
        if is_separator_row(trimmed) {
            in_data_rows = true;
            continue;
        }
        if in_data_rows {
            collect_backtick_tokens(trimmed, &mut tokens);
        }
    }
    tokens
}

/// Every field of a struct must be mentioned (in backticks) on the given
/// docs page; used where curated pages document config structs by hand.
fn check_struct_fields(
    root: &Path,
    rel: &str,
    struct_name: &str,
    docs_rel: &str,
    errors: &mut usize,
) -> Result<()> {
    let docs = read_rel(root, docs_rel)?;
    let file = parse_file(root, rel)?;
    let config = find_struct(&file, struct_name)
        .context(format!("struct {struct_name} not found in {rel}"))?;
    let missing: Vec<String> = config
        .fields
        .iter()
        .filter(|field| {
            let ident = field.ident.as_ref().unwrap().to_string();
            !docs.contains(&format!("`{ident}`"))
        })
        .map(|field| format!("`{}`", field.ident.as_ref().unwrap()))
        .collect();
    if !missing.is_empty() {
        println!("{struct_name} fields missing from {docs_rel}: {missing:?}");
        *errors += 1;
    }
    Ok(())
}

