//! Workspace automation: `cargo xtask docs` regenerates the code-derived
//! reference docs under `docs/generated/`, and `cargo xtask docs --check`
//! fails when the committed files differ from what the code produces.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use quote::ToTokens;
use rog_platform::asus_armoury::FirmwareAttribute;
use syn::{Item, ItemEnum, ItemStruct, punctuated::Punctuated, token::Comma};

const GENERATED_HEADER: &str = "<!-- generated by cargo xtask docs; do not edit -->";
const STALE_MESSAGE: &str = "Generated docs are stale. Run cargo xtask docs and commit the result.";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = match args.as_slice() {
        [task] if task == "docs" => false,
        [
            task,
            flag,
        ] if task == "docs" && flag == "--check" => true,
        _ => usage(),
    };
    let root = workspace_root();
    let files = match generate(&root) {
        Ok(files) => files,
        Err(err) => {
            eprintln!("error: {err:#}");
            std::process::exit(1);
        }
    };
    if check {
        check_all(&root, &files);
    } else if let Err(err) = write_all(&root, &files) {
        eprintln!("error: {err:#}");
        std::process::exit(1);
    }
}

fn usage() -> ! {
    eprintln!("usage: cargo xtask docs [--check]");
    std::process::exit(2);
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
}

fn generate(root: &Path) -> Result<BTreeMap<PathBuf, String>> {
    let default_ron = ron::ser::to_string_pretty(
        &asusd::config::Config::default(),
        ron::ser::PrettyConfig::new(),
    )
    .context("serializing asusd::config::Config::default()")?;

    let defaults = serde_json::to_value(asusd::config::Config::default())
        .context("serializing asusd::config::Config::default() as JSON")?;
    let anime_defaults = serde_json::to_value(asusd::aura_anime::config::AniMeConfig::default())
        .context("serializing AniMeConfig::default() as JSON")?;
    let slash_defaults = serde_json::to_value(asusd::aura_slash::config::SlashConfig::default())
        .context("serializing SlashConfig::default() as JSON")?;
    let scsi_defaults = serde_json::to_value(asusd::aura_scsi::config::ScsiConfig::default())
        .context("serializing ScsiConfig::default() as JSON")?;
    let aura_defaults = serde_json::to_value(asusd::aura_laptop::config::AuraConfig::default())
        .context("serializing AuraConfig::default() as JSON")?;

    let mut files = BTreeMap::new();
    files.insert(
        PathBuf::from("docs/generated/asusd-default.md"),
        default_ron_md(&default_ron),
    );
    files.insert(
        PathBuf::from("docs/generated/asusd-fields.md"),
        asusd_fields_md(root, &defaults)?,
    );
    files.insert(
        PathBuf::from("docs/generated/asusctl-cli.md"),
        asusctl_cli_md(root)?,
    );
    files.insert(
        PathBuf::from("docs/generated/armoury-attributes.md"),
        armoury_attributes_md(root)?,
    );
    files.insert(
        PathBuf::from("docs/generated/services.md"),
        services_md(root)?,
    );
    files.insert(
        PathBuf::from("docs/generated/anime-config.md"),
        anime_config_md(root, json_map(&anime_defaults)?)?,
    );
    files.insert(
        PathBuf::from("docs/generated/anime-builtins.md"),
        anime_builtins_md(root)?,
    );
    files.insert(
        PathBuf::from("docs/generated/aura-config.md"),
        aura_config_md(root, json_map(&aura_defaults)?)?,
    );
    files.insert(
        PathBuf::from("docs/generated/aura-effect.md"),
        effect_table_md(root, "rog-aura/src/builtin_modes.rs")?,
    );
    files.insert(
        PathBuf::from("docs/generated/aura-enums.md"),
        aura_enums_md(root)?,
    );
    files.insert(
        PathBuf::from("docs/generated/scsi-config.md"),
        scsi_config_md(root, json_map(&scsi_defaults)?)?,
    );
    files.insert(
        PathBuf::from("docs/generated/scsi-effect.md"),
        effect_table_md(root, "rog-scsi/src/builtin_modes.rs")?,
    );
    files.insert(
        PathBuf::from("docs/generated/scsi-modes.md"),
        mode_list_md(root, "rog-scsi/src/builtin_modes.rs", "AuraMode")?,
    );
    files.insert(
        PathBuf::from("docs/generated/slash-config.md"),
        slash_config_md(root, json_map(&slash_defaults)?)?,
    );
    files.insert(
        PathBuf::from("docs/generated/slash-modes.md"),
        mode_list_md(root, "rog-slash/src/data.rs", "SlashMode")?,
    );
    Ok(files)
}

fn write_all(root: &Path, files: &BTreeMap<PathBuf, String>) -> Result<()> {
    for (rel, content) in files {
        let path = root.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
        }
        fs::write(&path, content).with_context(|| format!("writing {}", rel.display()))?;
        println!("wrote {}", rel.display());
    }
    Ok(())
}

fn check_all(root: &Path, files: &BTreeMap<PathBuf, String>) {
    let mut errors = 0usize;
    for (rel, expected) in files {
        let label = rel.display().to_string();
        let current = match fs::read_to_string(root.join(rel)) {
            Ok(text) => text,
            Err(_) => {
                println!("{label}: missing");
                String::new()
            }
        };
        if current != *expected {
            let diff = similar::TextDiff::from_lines(&current, expected);
            print!(
                "{diff}",
                diff = diff.unified_diff().context_radius(3).header(
                    &format!("{label} (committed)"),
                    &format!("{label} (generated)")
                )
            );
            errors += 1;
        }
    }
    for check in [
        check_ledcode_table,
        check_effect_table,
        check_user_config_fields,
        check_platform_profile,
        check_cpuepp,
        check_action_loader,
        check_cli_sections,
        check_curve_fields,
        check_summary_files,
    ] {
        if let Err(err) = check(root, &mut errors) {
            eprintln!("error: {err:#}");
            errors += 1;
        }
    }
    if errors > 0 {
        println!("{STALE_MESSAGE}");
        std::process::exit(1);
    }
}

