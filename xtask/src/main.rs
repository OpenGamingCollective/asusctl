/// Every page linked from SUMMARY.md must exist.
fn check_summary_files(root: &Path, errors: &mut usize) -> Result<()> {
    let summary = read_rel(root, "docs/SUMMARY.md")?;
    for line in summary.lines() {
        let Some((_, rest)) = line.split_once("](") else {
            continue;
        };
        let Some(path) = rest.strip_suffix(')') else {
            continue;
        };
        if path.starts_with('#') || path.contains("://") {
            continue;
        }
        if !root.join("docs").join(path).is_file() {
            println!("SUMMARY.md links to missing file: docs/{path}");
            *errors += 1;
        }
    }
    Ok(())
}

fn check_effect_table(root: &Path, errors: &mut usize) -> Result<()> {
    let docs = read_rel(root, "docs/configuration/asusd-user.md")?;
    let mut documented = BTreeSet::new();
    let mut in_table = false;
    for line in docs.lines() {
        let trimmed = line.trim();
        if !in_table {
            in_table = trimmed == "| Effect | Fields | Description |";
            continue;
        }
        if !trimmed.starts_with('|') {
            break;
        }
        if is_separator_row(trimmed) {
            continue;
        }
        let Some(first) = trimmed
            .strip_prefix('|')
            .and_then(|rest| rest.split('|').next())
        else {
            break;
        };
        let name = first.trim().trim_matches('`');
        if !name.is_empty() {
            documented.insert(name.to_owned());
        }
    }

    let file = parse_file(root, "rog-aura/src/effects/mod.rs")?;
    let enumeration = find_enum(&file, "Effect").context("enum Effect not found")?;
    let variants: BTreeSet<String> = enumeration
        .variants
        .iter()
        .map(|variant| variant.ident.to_string())
        .collect();

    report_mismatch("Effect", &variants, &documented, errors);
    Ok(())
}

fn report_mismatch(
    name: &str,
    code: &BTreeSet<String>,
    docs: &BTreeSet<String>,
    errors: &mut usize,
) {
    let missing: Vec<&String> = code.difference(docs).collect();
    let extra: Vec<&String> = docs.difference(code).collect();
    if missing.is_empty() && extra.is_empty() {
        return;
    }
    println!("{name} table mismatch: missing {missing:?}, extra {extra:?}");
    *errors += 1;
}

fn collect_backtick_tokens(line: &str, tokens: &mut BTreeSet<String>) {
    let mut rest = line;
    while let Some(start) = rest.find('`') {
        let after = &rest[start + 1..];
        let Some(end) = after.find('`') else {
            break;
        };
        let token = &after[..end];
        if is_variant_token(token) {
            tokens.insert(token.to_owned());
        }
        rest = &after[end + 1..];
    }
}

fn is_variant_token(token: &str) -> bool {
    let mut chars = token.chars();
    chars.next().is_some_and(|first| first.is_ascii_uppercase())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn is_separator_row(line: &str) -> bool {
    let inner = line.trim_start_matches('|').trim_end_matches('|');
    !inner.is_empty() && inner.chars().all(|c| matches!(c, '-' | ':' | ' ' | '|'))
}

// --- syn helpers -------------------------------------------------------------

fn read_rel(root: &Path, rel: &str) -> Result<String> {
    fs::read_to_string(root.join(rel)).with_context(|| format!("reading {rel}"))
}

fn parse_file(root: &Path, rel: &str) -> Result<syn::File> {
    syn::parse_file(&read_rel(root, rel)?).with_context(|| format!("parsing {rel}"))
}

fn find_struct<'a>(file: &'a syn::File, name: &str) -> Option<&'a ItemStruct> {
    file.items.iter().find_map(|item| match item {
        Item::Struct(item) if item.ident == name => Some(item),
        _ => None,
    })
}

fn find_enum<'a>(file: &'a syn::File, name: &str) -> Option<&'a ItemEnum> {
    file.items.iter().find_map(|item| match item {
        Item::Enum(item) if item.ident == name => Some(item),
        _ => None,
    })
}

fn field_doc(field: &syn::Field) -> Result<String> {
    let mut doc = String::new();
    for attr in &field.attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        let meta = attr
            .meta
            .require_name_value()
            .context("doc comment is not a name-value pair")?;
        if let syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Str(lit),
            ..
        }) = &meta.value
        {
            if !doc.is_empty() {
                doc.push(' ');
            }
            doc.push_str(lit.value().trim());
        }
    }
    Ok(doc)
}

fn has_serde_skip(field: &syn::Field) -> bool {
    field.attrs.iter().any(|attr| {
        attr.path().is_ident("serde")
            && attr
                .parse_args_with(Punctuated::<syn::Meta, Comma>::parse_terminated)
                .map(|metas| metas.iter().any(|meta| meta.path().is_ident("skip")))
                .unwrap_or(false)
    })
}

fn is_option(ty: &syn::Type) -> bool {
    let syn::Type::Path(path) = ty else {
        return false;
    };
    path.path
        .segments
        .last()
        .is_some_and(|segment| segment.ident == "Option")
}

/// Render a type for the docs table, resolving local type aliases so that
/// `Tunings` shows as `map of PlatformProfile to Tuning`.
fn render_type(file: &syn::File, ty: &syn::Type) -> String {
    if let Some(resolved) = resolve_alias(file, ty) {
        return render_type(file, resolved);
    }
    if let syn::Type::Path(path) = ty
        && let Some(segment) = path.path.segments.last()
        && matches!(segment.ident.to_string().as_str(), "HashMap" | "BTreeMap")
        && let syn::PathArguments::AngleBracketed(args) = &segment.arguments
    {
        let types: Vec<String> = args
            .args
            .iter()
            .filter_map(|arg| match arg {
                syn::GenericArgument::Type(inner) => Some(render_type(file, inner)),
                _ => None,
            })
            .collect();
        if types.len() == 2 {
            return format!("map of {} to {}", types[0], types[1]);
        }
    }
    ty.to_token_stream()
        .to_string()
        .replace(" < ", "<")
        .replace(" >", ">")
        .replace(" , ", ", ")
}

/// Resolve `ty` through a `type X = ...;` alias declared in the same file.
fn resolve_alias<'a>(file: &'a syn::File, ty: &'a syn::Type) -> Option<&'a syn::Type> {
    let syn::Type::Path(path) = ty else {
        return None;
    };
    if path.path.segments.len() != 1 {
        return None;
    }
    let name = &path.path.segments[0].ident;
    file.items.iter().find_map(|item| match item {
        syn::Item::Type(item) if item.ident == *name => Some(item.ty.as_ref()),
        _ => None,
    })
}
