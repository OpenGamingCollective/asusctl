/// Variant names of an enum, plus which variant is marked `#[default]`.
fn enum_variants(root: &Path, rel: &str, enum_name: &str) -> Result<(Vec<String>, Option<String>)> {
    let file = parse_file(root, rel)?;
    let enumeration =
        find_enum(&file, enum_name).context(format!("enum {enum_name} not found in {rel}"))?;
    let mut variants = Vec::new();
    let mut default = None;
    for variant in &enumeration.variants {
        let name = variant.ident.to_string();
        if variant
            .attrs
            .iter()
            .any(|attr| attr.path().is_ident("default"))
        {
            default = Some(name.clone());
        }
        variants.push(name);
    }
    Ok((variants, default))
}

/// "`Off`, `Static` (default), …, and `DoubleFade`." sentence for prose.
fn mode_list_md(root: &Path, rel: &str, enum_name: &str) -> Result<String> {
    let (variants, default) = enum_variants(root, rel, enum_name)?;
    let mut parts: Vec<String> = variants
        .iter()
        .map(|name| {
            if Some(name) == default.as_ref() {
                format!("`{name}` (default)")
            } else {
                format!("`{name}`")
            }
        })
        .collect();
    let last = parts
        .pop()
        .context(format!("{enum_name} has no variants"))?;
    let list = if parts.is_empty() {
        last
    } else {
        format!("{} and {last}", parts.join(", "))
    };
    Ok(format!("{GENERATED_HEADER}\n{list}.\n"))
}

/// `builtin_anims` table: the built-in animations available per power state.
fn anime_builtins_md(root: &Path) -> Result<String> {
    let rows = [
        ("boot", "AnimBooting"),
        ("awake", "AnimAwake"),
        ("sleep", "AnimSleeping"),
        ("shutdown", "AnimShutdown"),
    ];
    let mut out =
        format!("{GENERATED_HEADER}\n| Power state | Animations | Default |\n|---|---|---|\n");
    for (state, enum_name) in rows {
        let (variants, default) = enum_variants(root, "rog-anime/src/usb.rs", enum_name)?;
        let rendered = variants
            .iter()
            .map(|name| format!("`{name}`"))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "| `{state}` | {rendered} | `{}` |\n",
            default.as_deref().unwrap_or("-")
        ));
    }
    Ok(out)
}

